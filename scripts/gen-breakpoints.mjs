#!/usr/bin/env node
/**
 * Stamps the seams from src/config/breakpoints.js into the two files that
 * cannot import it: the @custom-media tokens every stylesheet reads, and
 * public/scale-shell.html (a static document, generated from
 * src/templates/scale-shell.html). Idempotent; the literal sweep re-runs
 * this in memory and fails if either output is stale.
 *
 *   node scripts/gen-breakpoints.mjs          # write
 *   node scripts/gen-breakpoints.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { QUERIES, MOBILE_MAX_WIDTH, SHELL_MIN_WIDTH, TABLET_MIN_WIDTH, PHONE_MAX_WIDTH } from '../src/config/breakpoints.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

export function renderBreakpointsCss() {
  return `/* GENERATED by scripts/gen-breakpoints.mjs from src/config/breakpoints.js — do not edit.
   shell ${SHELL_MIN_WIDTH}+ · tablet ${TABLET_MIN_WIDTH}–${MOBILE_MAX_WIDTH} · phone ≤${PHONE_MAX_WIDTH} */
@custom-media --phone ${QUERIES.phone};
@custom-media --tablet ${QUERIES.tablet};
@custom-media --mobile ${QUERIES.mobile};
@custom-media --desktop ${QUERIES.desktop};
`;
}
export function renderScaleShell() {
  const tpl = readFileSync(join(ROOT, 'src/templates/scale-shell.html'), 'utf8');
  if (!tpl.includes('__MOBILE_MAX__')) throw new Error('scale-shell template lacks __MOBILE_MAX__');
  return tpl.replace(/__MOBILE_MAX__/g, String(MOBILE_MAX_WIDTH)).replace('<!-- GENERATED -->', '<!-- GENERATED by scripts/gen-breakpoints.mjs from src/templates/scale-shell.html — edit the template -->');
}
const outputs = [
  ['src/styles/tokens/breakpoints.css', renderBreakpointsCss()],
  ['public/scale-shell.html', renderScaleShell()],
];
let stale = 0;
for (const [rel, content] of outputs) {
  const path = join(ROOT, rel);
  let current = null; try { current = readFileSync(path, 'utf8'); } catch {}
  if (current === content) { console.log(`  fresh  ${rel}`); continue; }
  if (check) { console.log(`  STALE  ${rel}`); stale++; continue; }
  writeFileSync(path, content); console.log(`  wrote  ${rel}`);
}
if (check && stale) process.exit(1);
